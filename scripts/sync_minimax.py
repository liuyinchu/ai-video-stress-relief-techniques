"""Derive frame-aligned subtitles and illustration retiming from reviewed speech data."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def read(p):
 path=ROOT/p
 if not path.exists() and p.startswith('output/minimax/'):
  path=ROOT/'reference/minimax'/Path(p).name
 return json.loads(path.read_text())
timeline=read('content/timeline-minimax.json')
analysis={s['id']:s for s in read('output/minimax/timing-analysis.json')['segments']}
imports={s['id']:s for s in read('output/minimax/import-report.json')['segments']}
segments={s['id']:s for s in timeline['segments']}
snap=lambda t:round(t*30)/30
def placed(id,t):
 a=imports[id]
 return segments[id]['start']+(t-a['edges']['trim_start_seconds'])/a['fitted']['atempo']
# Reviewed paragraph groups; speech content remains the director's approved text.
groups={
 'intro':[(0,1,'压力上来，先别急着说服自己'),(2,2,'给身体一点缓冲')],
 'breath':[(1,1,'鼻子轻轻吸气'),(2,2,'再补一小口'),(3,3,'嘴巴慢慢呼出'),(4,5,'不要用力，头晕就停')],
 'cool':[(1,1,'用凉毛巾轻敷脸颊'),(2,2,'保持自然呼吸')],
 'ear':[(1,2,'轻揉耳廓，以舒服为准')],
 'shake':[(1,2,'轻轻抖动手脚，放松肩膀'),(3,3,'别甩头')],
 'paper':[(1,1,'把烦心事写下来'),(2,2,'揉成纸团'),(3,3,'再丢掉')],
 'nature':[(1,2,'看一会儿树叶、云朵'),(3,3,'让目光慢下来')],
 'order':[(1,1,'只整理桌面一小块'),(2,2,'让眼前恢复一点秩序')],
 'outro':[(0,1,'不必全做，挑一个就好'),(2,2,'先松一口气'),(3,3,'再处理眼前的事')]
}
cues=[]
for id,gs in groups.items():
 assert analysis[id]['sha256']==imports[id]['raw']['sha256'], f'Stale speech timing for {id}'
 phrases=analysis[id]['acoustic_phrases']
 for j,(a,b,text) in enumerate(gs):
  start=segments[id]['start'] if j==0 else placed(id,phrases[a]['start'])
  end=placed(id,phrases[gs[j+1][0]]['start']) if j+1<len(gs) else min(segments[id]['end'],placed(id,phrases[b]['end'])+.25)
  cues.append(dict(start=snap(start),end=snap(end),text=text,segment=id))
def phrase_time(id,index,edge='start'):
 return snap(placed(id,analysis[id]['acoustic_phrases'][index][edge]))
breathStart=next(s['start'] for s in timeline['stations'] if s['id']=='breath')
paperStart=next(s['start'] for s in timeline['stations'] if s['id']=='paper')
retime={
 'breath':[[0,0],[phrase_time('breath',2)-breathStart,3],[phrase_time('breath',3)-breathStart,3.7],[10,10],[12,12]],
 'paper':[[0,0],[phrase_time('paper',2)-paperStart,.45],[phrase_time('paper',2,'end')-paperStart,2.55],[phrase_time('paper',3)-paperStart,2.9],[phrase_time('paper',3,'end')-paperStart,4.5],[8,8]]
}
config=dict(version='minimax-v2',timeline='../content/timeline-minimax.json',captions='../content/captions-minimax.json',retime=retime,
 cuts=sorted(set([c[k] for c in cues for k in ['start','end']]+[phrase_time('breath',2),phrase_time('breath',3),15,55.2])))
(ROOT/'content/captions-minimax.json').write_text(json.dumps(cues,ensure_ascii=False,indent=2)+'\n')
(ROOT/'content/minimax-render-config.js').write_text('// Generated by scripts/sync_minimax.py from the reviewed voice timings.\nwindow.FILM_EDITION = '+json.dumps(config,ensure_ascii=False,indent=2)+';\n')
(ROOT/'output/minimax/sync-report.json').write_text(json.dumps({'method':'Independent offline ASR plus acoustic pause edges; approximate phrase timing snapped to 30fps.','render_config':config,'subtitles':cues},ensure_ascii=False,indent=2))
def stamp(t):
 ms=round(t*1000);return f'{ms//3600000:02}:{ms//60000%60:02}:{ms//1000%60:02},{ms%1000:03}'
(ROOT/'output/narration-minimax.srt').write_text('\n'.join(f'{i}\n{stamp(c["start"])} --> {stamp(c["end"])}\n{c["text"]}\n' for i,c in enumerate(cues,1)))
print(json.dumps({'cues':len(cues),'retime':retime},ensure_ascii=False))
